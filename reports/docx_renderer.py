"""
reports/docx_renderer.py — Word document generation using python-docx.

Takes structured report data and builds a formatted Word document.
"""

import io
import re
from typing import Optional, Tuple
import structlog

log = structlog.get_logger()

try:
    from docx import Document
    from docx.shared import Pt, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    DOCX_AVAILABLE = True
except ImportError:
    DOCX_AVAILABLE = False
    log.warning("python-docx not installed — Word generation unavailable")


def render_docx(report_data: dict) -> Tuple[Optional[bytes], Optional[str]]:
    """
    Generate a Word document from report data.

    Args:
        report_data: Dict with keys:
            - title: str
            - client_name: str
            - business_name: str
            - date: str
            - sections: List[{heading: str, content: str}]

    Returns: (docx_bytes_or_none, error_or_none)
    """
    if not DOCX_AVAILABLE:
        return None, "python-docx not installed. Run: pip install python-docx"

    try:
        doc = Document()

        # ── Document styles ───────────────────────────────────────────────────
        doc.core_properties.title  = report_data.get("title", "SashaOps Intelligence Report")
        doc.core_properties.author = "SashaOps Intelligence Platform"

        # Title page
        title_para = doc.add_paragraph()
        title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        title_run = title_para.add_run(report_data.get("title", "Intelligence Report"))
        title_run.bold     = True
        title_run.font.size = Pt(24)

        doc.add_paragraph()  # Spacer

        meta = doc.add_paragraph()
        meta.alignment = WD_ALIGN_PARAGRAPH.CENTER
        meta.add_run(f"Subject: {report_data.get('business_name', '')}\n").bold = True
        meta.add_run(f"Prepared for: {report_data.get('client_name', '')}\n")
        meta.add_run(f"Date: {report_data.get('date', '')}\n")
        meta.add_run("Prepared by: SashaOps Intelligence Platform")

        doc.add_page_break()

        # ── Sections ──────────────────────────────────────────────────────────
        for section in report_data.get("sections", []):
            heading  = section.get("heading", "")
            content  = section.get("content", "")
            icon     = section.get("icon", "")

            if heading:
                h = doc.add_heading(f"{icon} {heading}".strip(), level=1)
                h.runs[0].font.color.rgb = RGBColor(0, 100, 0)

            if content:
                _add_markdown_content(doc, content)

            doc.add_paragraph()

        # Footer note
        footer_para = doc.add_paragraph()
        footer_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        footer_run  = footer_para.add_run(
            "This report was generated by SashaOps Intelligence Platform. "
            "All analysis is AI-assisted and should be verified independently before making business decisions."
        )
        footer_run.font.size   = Pt(9)
        footer_run.font.italic = True

        # Serialize to bytes
        buf = io.BytesIO()
        doc.save(buf)
        buf.seek(0)

        docx_bytes = buf.read()
        log.info("DOCX rendered", size_kb=len(docx_bytes) // 1024)
        return docx_bytes, None

    except Exception as e:
        log.error("DOCX render failed", error=str(e))
        return None, str(e)


def _clean_inline(s: str) -> str:
    """Strip inline markdown markers for plain Word text."""
    s = re.sub(r"\*\*(.+?)\*\*", r"\1", s)
    s = re.sub(r"(?<!\*)\*(?!\*)(.+?)\*", r"\1", s)
    s = re.sub(r"_(.+?)_", r"\1", s)
    return s


def _flush_table(doc, rows: list) -> None:
    """Render accumulated pipe-table rows as a real Word table."""
    if not rows:
        return
    ncols = max(len(r) for r in rows)
    table = doc.add_table(rows=0, cols=ncols)
    try:
        table.style = "Light Grid Accent 1"
    except Exception:
        pass
    for i, cells in enumerate(rows):
        cells = cells + [""] * (ncols - len(cells))
        wrow = table.add_row().cells
        for j, c in enumerate(cells):
            wrow[j].text = _clean_inline(c)
            if i == 0:  # header row bold
                for para in wrow[j].paragraphs:
                    for run in para.runs:
                        run.bold = True


def _add_markdown_content(doc, text: str) -> None:
    """Add markdown-formatted text (headings, tables, lists, bold) to a Word document."""
    table_rows: list = []
    in_code = False

    def _flush():
        nonlocal table_rows
        if table_rows:
            _flush_table(doc, table_rows)
            table_rows = []

    for line in text.split("\n"):
        line = line.rstrip()

        if line.strip() == "```":
            _flush(); in_code = not in_code
            continue
        if in_code:
            doc.add_paragraph(line, style="No Spacing" if _has_style(doc, "No Spacing") else None)
            continue

        is_table_row = line.strip().startswith("|") and line.strip().endswith("|")
        if is_table_row:
            cells = [c.strip() for c in line.strip()[1:-1].split("|")]
            if all(set(c.replace(" ", "")) <= set("-:") for c in cells):
                continue  # separator row
            table_rows.append(cells)
            continue
        else:
            _flush()

        if line.startswith("## "):
            doc.add_heading(_clean_inline(line[3:]), level=2)
        elif line.startswith("### "):
            doc.add_heading(_clean_inline(line[4:]), level=3)
        elif line.startswith("**") and line.endswith("**"):
            p   = doc.add_paragraph()
            run = p.add_run(line.strip("*"))
            run.bold = True
        elif line.startswith("- ") or line.startswith("* "):
            doc.add_paragraph(_clean_inline(line[2:]), style="List Bullet")
        elif line.strip() == "":
            doc.add_paragraph()
        else:
            doc.add_paragraph(_clean_inline(line))

    _flush()


def _has_style(doc, name: str) -> bool:
    try:
        return name in [s.name for s in doc.styles]
    except Exception:
        return False


def save_docx(docx_bytes: bytes, output_path: str) -> Tuple[bool, Optional[str]]:
    """Save DOCX bytes to disk. Returns (success, error_or_none)."""
    try:
        import os
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        with open(output_path, "wb") as f:
            f.write(docx_bytes)
        return True, None
    except Exception as e:
        return False, str(e)
